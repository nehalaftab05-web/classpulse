// Fall 2026 current date helpers
function getIsoDate(daysFromNow: number, hours: number, minutes: number = 0): string {
  const d = new Date();
  d.setDate(d.getDate() + daysFromNow);
  d.setHours(hours, minutes, 0, 0);
  return d.toISOString();
}

